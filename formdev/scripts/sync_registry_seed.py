#!/usr/bin/env python3
"""Regenerate every copy of the style and font registry from formdev/registry/*.json.

    python3 formdev/scripts/sync_registry_seed.py          # rewrite
    python3 formdev/scripts/sync_registry_seed.py --check  # exit 1 if out of date

The registry JSON files are the single source of truth. Generated from them:
  - the seed blocks in 0060-formdev.sql and sqlite_schema.sql (fresh installs; insert if missing),
  - 0062-formdev-registry.sql and sqlite_0003_registry.sql (upgrades: a style row is replaced when the
    registry carries a newer version, built-in font rows are refreshed),
  - 0063-formdev-lookup.sql and sqlite_0004_lookup.sql (Phase 2.3 lookup tables from formdev/registry/lookups/),
  - frontend/src/formdev/registry/defaults.ts (offline preview and standalone use),
  - the validator message catalog (formdev/spec/messages.json) as services/flora-api/app/formdev/messages.py
    and frontend/src/formdev/core/messages.ts.
Font rows are stored as one metadata object: the entry's metadata plus its assets and fallback.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BEGIN, END = "-- BEGIN registry seed (generated by formdev/scripts/sync_registry_seed.py)", "-- END registry seed"
SEED_TARGETS = {
    REPO / "infrastructure/postgres/0060-formdev.sql": "::jsonb",
    REPO / "services/flora-api/app/formdev/adapters/sqlite_schema.sql": "",
}
UPGRADE_TARGETS = {
    REPO / "infrastructure/postgres/0062-formdev-registry.sql": ("::jsonb", True),
    REPO / "services/flora-api/app/formdev/adapters/sqlite_0003_registry.sql": ("", False),
}
LOOKUP_TARGETS = {
    REPO / "infrastructure/postgres/0063-formdev-lookup.sql": ("::jsonb", True),
    REPO / "services/flora-api/app/formdev/adapters/sqlite_0004_lookup.sql": ("", False),
}
LOOKUP_DIR = REPO / "formdev/registry/lookups"
MYSQL_TARGET = REPO / "services/flora-api/app/formdev/adapters/mysql_0002_registry.sql"
TS_TARGET = REPO / "frontend/src/formdev/registry/defaults.ts"
MESSAGES_SOURCE = REPO / "formdev/spec/messages.json"
MESSAGES_PY = REPO / "services/flora-api/app/formdev/messages.py"
MESSAGES_TS = REPO / "frontend/src/formdev/core/messages.ts"


def literal(value: object, cast: str) -> str:
    return "'" + json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("'", "''") + "'" + cast


def registry() -> tuple[list[dict], list[dict]]:
    styles = json.loads((REPO / "formdev/registry/styles.json").read_text(encoding="utf-8"))
    fonts = json.loads((REPO / "formdev/registry/fonts.json").read_text(encoding="utf-8"))
    return styles, fonts


def stored_font(entry: dict) -> dict:
    return {**entry["metadata"], "assets": entry.get("assets", []), "fallback": entry.get("fallback", [])}


def rows(cast: str) -> tuple[str, str]:
    styles, fonts = registry()
    style_rows = ",\n".join(f"  ('{s['style_id']}', {s['version']}, {literal(s['definition'], cast)}, 0)" for s in styles)
    font_rows = ",\n".join(f"  ('{f['font_id']}', {literal(stored_font(f), cast)}, 0)" for f in fonts)
    return style_rows, font_rows


def seed_block(cast: str) -> str:
    style_rows, font_rows = rows(cast)
    return (
        f"{BEGIN}\n"
        f"INSERT INTO formdev_font (font_id, metadata, updated_at) VALUES\n{font_rows}\nON CONFLICT (font_id) DO NOTHING;\n\n"
        f"INSERT INTO formdev_style (style_id, version, definition, updated_at) VALUES\n{style_rows}\nON CONFLICT (style_id) DO NOTHING;\n"
        f"{END}"
    )


def upgrade_file(cast: str, transactional: bool) -> str:
    style_rows, font_rows = rows(cast)
    body = (
        f"INSERT INTO formdev_font (font_id, metadata, updated_at) VALUES\n{font_rows}\n"
        "ON CONFLICT (font_id) DO UPDATE SET metadata = excluded.metadata, updated_at = excluded.updated_at\n"
        "  WHERE formdev_font.metadata <> excluded.metadata;\n\n"
        f"INSERT INTO formdev_style (style_id, version, definition, updated_at) VALUES\n{style_rows}\n"
        "ON CONFLICT (style_id) DO UPDATE SET version = excluded.version, definition = excluded.definition, updated_at = excluded.updated_at\n"
        "  WHERE formdev_style.version < excluded.version;\n"
    )
    head = ("-- FormDev Phase 1: style registry with inheritance and tokens, Thai official font metadata.\n"
            "-- Generated by formdev/scripts/sync_registry_seed.py from formdev/registry/*.json; do not edit.\n"
            "-- Idempotent: a style row is replaced only by a newer registry version; built-in font rows are refreshed.\n")
    return head + ("BEGIN;\n\n" + body + "\nCOMMIT;\n" if transactional else body)


def lookups() -> list[dict]:
    return [json.loads(path.read_text(encoding="utf-8")) for path in sorted(LOOKUP_DIR.glob("*.json"))]


def lookup_file(cast: str, transactional: bool) -> str:
    """Phase 2.3 lookup table plus the registry's lookups; a row is replaced only by a newer version (so an
    imported full dataset, which carries a higher version, is never overwritten by the sample)."""
    json_type = "jsonb" if cast else "text"
    int_type = "bigint" if cast else "integer"
    rows = ",\n".join(f"  ('{item['lookup_id']}', {item['version']}, {literal(item['metadata'], cast)}, {literal(item['entries'], cast)}, 0, 'system')"
                      for item in lookups())
    body = (
        "CREATE TABLE IF NOT EXISTS formdev_lookup (\n"
        "  lookup_id text PRIMARY KEY,\n"
        "  version integer NOT NULL,\n"
        f"  metadata {json_type} NOT NULL,\n"
        f"  entries {json_type} NOT NULL,\n"
        f"  updated_at {int_type} NOT NULL,\n"
        "  updated_by text\n"
        ");\n\n"
        f"INSERT INTO formdev_lookup (lookup_id, version, metadata, entries, updated_at, updated_by) VALUES\n{rows}\n"
        "ON CONFLICT (lookup_id) DO UPDATE SET version = excluded.version, metadata = excluded.metadata, entries = excluded.entries,\n"
        "  updated_at = excluded.updated_at, updated_by = excluded.updated_by\n"
        "  WHERE formdev_lookup.version < excluded.version;\n"
    )
    if cast:
        body += "\nGRANT SELECT, INSERT, UPDATE ON formdev_lookup TO flora_view, flora_app;\n"
    head = ("-- FormDev Phase 2.3: lookup tables for dependent options and derived values (formdev/registry/lookups/*.json).\n"
            "-- Generated by formdev/scripts/sync_registry_seed.py; do not edit. Idempotent: a row is replaced only by a newer version.\n")
    return head + ("BEGIN;\n\n" + body + "\nCOMMIT;\n" if transactional else body)


def mysql_seed() -> str:
    """MySQL migration 2 (and later re-runs): fonts refreshed, styles and lookups replaced only by a newer version."""
    style_rows, font_rows = rows("")
    lookup_rows = ",\n".join(f"  ('{item['lookup_id']}', {item['version']}, {literal(item['metadata'], '')}, {literal(item['entries'], '')}, 0, 'system')"
                            for item in lookups())
    # MySQL string literals treat backslash as an escape character; JSON escapes must survive.
    body = (
        f"INSERT INTO formdev_font (font_id, metadata, updated_at) VALUES\n{font_rows}\nAS new\n"
        "ON DUPLICATE KEY UPDATE metadata = new.metadata, updated_at = IF(formdev_font.metadata <> new.metadata, new.updated_at, formdev_font.updated_at);\n\n"
        f"INSERT INTO formdev_style (style_id, version, definition, updated_at) VALUES\n{style_rows}\nAS new\n"
        "ON DUPLICATE KEY UPDATE definition = IF(new.version > formdev_style.version, new.definition, formdev_style.definition),\n"
        "  updated_at = IF(new.version > formdev_style.version, new.updated_at, formdev_style.updated_at),\n"
        "  version = GREATEST(formdev_style.version, new.version);\n\n"
        f"INSERT INTO formdev_lookup (lookup_id, version, metadata, entries, updated_at, updated_by) VALUES\n{lookup_rows}\nAS new\n"
        "ON DUPLICATE KEY UPDATE metadata = IF(new.version > formdev_lookup.version, new.metadata, formdev_lookup.metadata),\n"
        "  entries = IF(new.version > formdev_lookup.version, new.entries, formdev_lookup.entries),\n"
        "  updated_at = IF(new.version > formdev_lookup.version, new.updated_at, formdev_lookup.updated_at),\n"
        "  updated_by = IF(new.version > formdev_lookup.version, new.updated_by, formdev_lookup.updated_by),\n"
        "  version = GREATEST(formdev_lookup.version, new.version);\n"
    ).replace("\\", "\\\\")
    return ("-- FormDev registry for MySQL (migration 2): styles, fonts and lookup tables from formdev/registry/.\n"
            "-- Generated by formdev/scripts/sync_registry_seed.py; do not edit.\n" + body)


def ts_module() -> str:
    styles, fonts = registry()
    calculators = json.loads((REPO / "formdev/registry/calculators.json").read_text(encoding="utf-8"))
    return (
        "/** Generated by formdev/scripts/sync_registry_seed.py from formdev/registry/*.json; do not edit. */\n"
        'import type { CalculatorTemplate } from "../logic/calculators";\n'
        'import type { FontEntry, StyleEntry } from "../core/types";\n\n'
        f"export const DEFAULT_STYLES: StyleEntry[] = {json.dumps(styles, ensure_ascii=False, indent=2)};\n\n"
        f"export const DEFAULT_FONTS: FontEntry[] = {json.dumps([{'font_id': f['font_id'], 'metadata': stored_font(f)} for f in fonts], ensure_ascii=False, indent=2)};\n\n"
        f"/** Calculator templates (Phase 2.5): instantiate with logic/calculators.instantiateTemplate. */\n"
        f"export const CALCULATOR_TEMPLATES: CalculatorTemplate[] = {json.dumps(calculators, ensure_ascii=False, indent=2)};\n"
    )


def messages() -> dict:
    return json.loads(MESSAGES_SOURCE.read_text(encoding="utf-8"))["messages"]


def messages_py() -> str:
    return (
        '"""Validator messages per issue code (generated by formdev/scripts/sync_registry_seed.py from\n'
        'formdev/spec/messages.json; do not edit)."""\n\n'
        f"MESSAGES: dict[str, dict[str, str]] = {json.dumps(messages(), ensure_ascii=False, indent=4)}\n"
    )


def messages_ts() -> str:
    return (
        "/** Validator messages per issue code (generated by formdev/scripts/sync_registry_seed.py from formdev/spec/messages.json; do not edit). */\n"
        f"export const MESSAGES: Readonly<Record<string, {{ en: string; th: string }}>> = {json.dumps(messages(), ensure_ascii=False, indent=2)};\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    wanted: dict[Path, str] = {}
    for path, cast in SEED_TARGETS.items():
        text = path.read_text(encoding="utf-8")
        if BEGIN not in text or END not in text:
            print(f"missing seed markers in {path}", file=sys.stderr)
            return 1
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        wanted[path] = head + seed_block(cast) + tail
    for path, (cast, transactional) in UPGRADE_TARGETS.items():
        wanted[path] = upgrade_file(cast, transactional)
    for path, (cast, transactional) in LOOKUP_TARGETS.items():
        wanted[path] = lookup_file(cast, transactional)
    wanted[MYSQL_TARGET] = mysql_seed()
    wanted[TS_TARGET] = ts_module()
    wanted[MESSAGES_PY] = messages_py()
    wanted[MESSAGES_TS] = messages_ts()
    stale = [path for path, text in wanted.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            print("registry copies out of date: " + ", ".join(str(path.relative_to(REPO)) for path in stale), file=sys.stderr)
            return 1
        print("registry copies up to date")
        return 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(wanted[path], encoding="utf-8")
    print("registry copies " + ("updated: " + ", ".join(path.name for path in stale) if stale else "up to date"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
